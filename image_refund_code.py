import os, shutil
from pathlib import Path
from sklearn.model_selection import train_test_split

# آدرسی که در مرحله قبل با موفقیت پیدا شد
dataset_path = "/content/dataset/caltech-101"
base_dir = Path("/content/caltech_split")

# پاکسازی برای اطمینان از کپی مجدد عکس‌ها
if base_dir.exists():
    shutil.rmtree(base_dir)

train_dir = base_dir / "train"
val_dir = base_dir / "val"
os.makedirs(train_dir, exist_ok=True)
os.makedirs(val_dir, exist_ok=True)

print("📂 Copying images to train/val folders... Please wait.")

# شمارنده برای چک کردن نهایی
total_copied = 0

for category in os.listdir(dataset_path):
    cat_path = os.path.join(dataset_path, category)
    if os.path.isdir(cat_path):
        # پیدا کردن تمام عکس‌ها
        images = [os.path.join(cat_path, f) for f in os.listdir(cat_path) if f.lower().endswith(('.jpg', '.jpeg', '.png'))]

        if len(images) < 10: # حذف کلاس‌های خیلی کوچک برای دقت بیشتر
            continue

        train_imgs, val_imgs = train_test_split(images, test_size=0.2, random_state=42)

        os.makedirs(train_dir / category, exist_ok=True)
        os.makedirs(val_dir / category, exist_ok=True)

        for img in train_imgs:
            shutil.copy(img, train_dir / category)
            total_copied += 1
        for img in val_imgs:
            shutil.copy(img, val_dir / category)
            total_copied += 1

print(f"✅ Dataset split complete! Total images moved: {total_copied}")

# STEP 6️⃣ — Build and train model with fine-tuning
import tensorflow as tf
from tensorflow.keras.preprocessing.image import ImageDataGenerator
from tensorflow.keras.applications import MobileNetV2
from tensorflow.keras.layers import Dense, GlobalAveragePooling2D, Dropout
from tensorflow.keras.models import Model
from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau

train_datagen = ImageDataGenerator(rescale=1./255, rotation_range=25, width_shift_range=0.2,
                                   height_shift_range=0.2, zoom_range=0.2, horizontal_flip=True)
val_datagen = ImageDataGenerator(rescale=1./255)

train_gen = train_datagen.flow_from_directory(
    train_dir, target_size=(224, 224), batch_size=32, class_mode='categorical'
)
val_gen = val_datagen.flow_from_directory(
    val_dir, target_size=(224, 224), batch_size=32, class_mode='categorical', shuffle=False
)

# Load MobileNetV2
base_model = MobileNetV2(weights='imagenet', include_top=False, input_shape=(224,224,3))

# Freeze most layers, fine-tune last 30
for layer in base_model.layers[:-30]:
    layer.trainable = False
for layer in base_model.layers[-30:]:
    layer.trainable = True

x = GlobalAveragePooling2D()(base_model.output)
x = Dropout(0.4)(x)
x = Dense(256, activation='relu')(x)
x = Dropout(0.3)(x)
out = Dense(train_gen.num_classes, activation='softmax')(x)

model = Model(inputs=base_model.input, outputs=out)

# Compile
model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=1e-4),
              loss='categorical_crossentropy', metrics=['accuracy'])

# Academic Callbacks for better results
callbacks = [
    EarlyStopping(monitor='val_loss', patience=10, restore_best_weights=True),
    ReduceLROnPlateau(monitor='val_loss', factor=0.2, patience=5)
]

# Train model (increased epochs with automated stopping)
history = model.fit(train_gen, validation_data=val_gen, epochs=70, callbacks=callbacks)
print("✅ Model training complete!")

